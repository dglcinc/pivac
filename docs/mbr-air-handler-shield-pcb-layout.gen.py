#!/usr/bin/env python3
"""Generate docs/mbr-air-handler-shield-pcb-layout.svg, the floor plan of the master bedroom air-handler shield
PCB (docs/mbr-air-handler-shield-pcb-plan.md).

Run from the repo root: python3 docs/mbr-air-handler-shield-pcb-layout.gen.py

Coordinates are millimetres, origin at the bottom-left corner of the shield, x to the right, y up, the
DIGITAL header along the top edge and the R4's USB-C and barrel jack under the left edge, as in Arduino's
mechanical drawing. The shield runs 17.78 mm past the R4's right edge, and the terminals sit on that tab.
Parts are drawn as body outlines at their planned centres; the routed board in hardware/ is the authority.
"""
from pathlib import Path

S = 10.0                       # px per mm
BW, BH = 86.36, 53.34          # shield
UNO_W = 68.58                  # R4 outline under it
BX, BY = 70, 120               # SVG position of the shield's top-left corner
W, H = int(BX + BW * S + 430), int(BY + BH * S + 300)

C_PRI = "#c0392b"      # 24 VAC side
C_RLY = "#7b3fa0"      # relays
C_IN = "#2e8b3a"       # logic inputs
C_AN = "#1f6fb4"       # air temperatures
C_OW = "#b8860b"       # 1-wire
C_PWR = "#d35400"      # 5 V side of the converter
C_GND = "#333333"
C_FAINT = "#9a9a9a"
C_PAD = "#c9a227"

out = []
add = out.append


def X(x):
    return BX + x * S


def Y(y):
    return BY + (BH - y) * S


def text(x, y, s, size=10, color="#222", anchor="middle", weight="normal", rotate=None):
    t = f' transform="rotate({rotate} {X(x):.1f} {Y(y):.1f})"' if rotate else ""
    add(f'<text x="{X(x):.1f}" y="{Y(y):.1f}" font-size="{size}" fill="{color}" text-anchor="{anchor}" '
        f'font-weight="{weight}" font-family="Helvetica, Arial, sans-serif"{t}>{s}</text>')


def rect(x0, y0, x1, y1, stroke, fill="none", sw=1.2, dash=None, rx=0, opacity=1.0):
    d = f' stroke-dasharray="{dash}"' if dash else ""
    add(f'<rect x="{X(x0):.1f}" y="{Y(y1):.1f}" width="{(x1 - x0) * S:.1f}" height="{(y1 - y0) * S:.1f}" '
        f'rx="{rx}" stroke="{stroke}" fill="{fill}" stroke-width="{sw}" fill-opacity="{opacity}"{d}/>')


def circle(x, y, r, stroke, fill="none", sw=1.2, dash=None):
    d = f' stroke-dasharray="{dash}"' if dash else ""
    add(f'<circle cx="{X(x):.1f}" cy="{Y(y):.1f}" r="{r * S:.1f}" stroke="{stroke}" fill="{fill}" '
        f'stroke-width="{sw}"{d}/>')


def part(ref, x, y, w, h, color, value=None, label_at="c"):
    rect(x - w / 2, y - h / 2, x + w / 2, y + h / 2, color, fill=color, sw=1.0, opacity=0.18, rx=2)
    rect(x - w / 2, y - h / 2, x + w / 2, y + h / 2, color, sw=1.0, rx=2)
    if label_at == "c":
        text(x, y + (0.25 if value else -0.35), ref, 8.5, color, weight="bold")
        if value:
            text(x, y - 0.95, value, 7, color)
    elif label_at == "a":
        text(x, y + h / 2 + 0.4, ref, 8.5, color, weight="bold")


# ---- page --------------------------------------------------------------------------------------------------------
add(f'<svg xmlns="http://www.w3.org/2000/svg" width="{W}" height="{H}" viewBox="0 0 {W} {H}">')
add(f'<rect width="{W}" height="{H}" fill="#ffffff"/>')
add(f'<text x="{BX}" y="40" font-size="20" font-weight="bold" font-family="Helvetica, Arial, sans-serif" '
    f'fill="#222">Master bedroom air-handler shield — PCB floor plan, component side</text>')
add(f'<text x="{BX}" y="64" font-size="12" font-family="Helvetica, Arial, sans-serif" fill="#444">'
    f'UNO R4 WiFi shield, 86.36 × 53.34 mm, 2 layers. Millimetres from the bottom-left corner. '
    f'Plan: docs/mbr-air-handler-shield-pcb-plan.md</text>')
add(f'<text x="{BX}" y="82" font-size="12" font-family="Helvetica, Arial, sans-serif" fill="#444">'
    f'Generated by docs/mbr-air-handler-shield-pcb-layout.gen.py. Body outlines at planned centres; '
    f'the routed board is the authority.</text>')

# ---- board, R4 outline and what lies under the shield -----------------------------------------------------------
rect(0, 0, BW, BH, "#1d6b3a", fill="#eef6ef", sw=2.2, rx=8)
rect(0, 0, UNO_W, BH, C_FAINT, sw=1.2, dash="6 4")
text(UNO_W - 0.6, 21.0, "R4 edge", 7, C_FAINT, anchor="end", rotate=-90)
rect(-1.0, 35.5, 7.5, 44.5, C_FAINT, sw=1.0, dash="3 3")
text(3.2, 34.3, "R4 USB-C (under)", 7, C_FAINT)
rect(-1.8, 3.2, 13.5, 12.6, C_FAINT, sw=1.0, dash="3 3")
text(5.9, 13.4, "R4 barrel jack (under), 11 mm tall", 7, C_FAINT)
# ICSP: 2 x 3 clearance holes, no copper, nothing on top over them
rect(60.8, 22.6, 66.5, 30.8, C_FAINT, fill="#ffffff", sw=1.0, dash="3 3")
for ix in (62.36, 64.90):
    for iy in (24.13, 26.67, 29.21):
        circle(ix, iy, 0.5, C_FAINT, fill="#ffffff", sw=1.0)
text(63.63, 31.4, "ICSP holes", 7, C_FAINT)

# mounting holes on the UNO pattern
for hx, hy in ((13.97, 2.54), (15.24, 50.8), (66.04, 7.62), (66.04, 35.56)):
    circle(hx, hy, 1.6, "#555", fill="#ffffff", sw=1.2)
    circle(hx, hy, 2.75, "#999", sw=0.8, dash="2 2")

# ---- 24 VAC side outline -----------------------------------------------------------------------------------------
pri = [(19.6, 32.0), (68.3, 32.0), (68.3, 36.2), (79.06, 36.2), (79.06, BH - 0.3), (65.0, BH - 0.3),
       (65.0, 48.3), (56.6, 48.3), (56.6, 38.4), (66.3, 38.4), (66.3, 34.8), (41.2, 34.8), (41.2, 40.2),
       (19.6, 40.2)]
pts = " ".join(f"{X(px):.1f},{Y(py):.1f}" for px, py in pri)
add(f'<polygon points="{pts}" fill="{C_PRI}" fill-opacity="0.06" stroke="{C_PRI}" stroke-width="1.4" '
    f'stroke-dasharray="7 4"/>')
text(20.0, 29.4, "24 VAC side (dashed); bus R · C · Y2 · W2 on the solder side along y 33–34", 8, C_PRI, anchor="start")

# ---- Arduino headers -----------------------------------------------------------------------------------------------
bottom = [("NC", 27.94), ("IOREF", 30.48), ("RST", 33.02), ("3V3", 35.56), ("5V", 38.10), ("GND", 40.64),
          ("GND", 43.18), ("VIN", 45.72), ("A0", 50.80), ("A1", 53.34), ("A2", 55.88), ("A3", 58.42),
          ("A4", 60.96), ("A5", 63.50)]
top = [("SCL", 18.80), ("SDA", 21.34), ("AREF", 23.88), ("GND", 26.42), ("D13", 28.96), ("D12", 31.50),
       ("D11", 34.04), ("D10", 36.58), ("D9", 39.12), ("D8", 41.66), ("D7", 45.72), ("D6", 48.26),
       ("D5", 50.80), ("D4", 53.34), ("D3", 55.88), ("D2", 58.42), ("D1", 60.96), ("D0", 63.50)]
used = {"5V": C_PWR, "GND": C_GND, "A0": C_AN, "A1": C_AN, "A2": C_IN, "A3": C_IN, "SDA": C_OW, "SCL": C_OW,
        "D8": C_IN, "D9": C_IN, "D2": C_OW}
for row, y, dy in ((bottom, 2.54, 1.55), (top, 50.80, 1.75)):
    for name, x in row:
        col = used.get(name, None)
        circle(x, y, 0.8, C_PAD, fill=col if col else "#ffffff", sw=1.0)
        circle(x, y, 0.5, C_PAD, fill="#ffffff", sw=0.6)
        text(x, y + dy, name, 6.5, col if col else C_FAINT, weight="bold" if col else "normal")

# ---- 24 VAC side: entry, rectifier, reservoir, converter ----------------------------------------------------------
part("F1", 76.2, 51.4, 4.8, 3.4, C_PRI, "PTC 0.2 A")
part("D1", 70.6, 51.4, 5.2, 2.8, C_PRI, "S1M")
part("D2", 69.6, 48.5, 5.2, 2.8, C_PRI, "TVS")
rect(68.65, 36.65, 78.95, 46.95, C_PRI, fill=C_PRI, sw=1.0, opacity=0.12, rx=3)
rect(68.65, 36.65, 78.95, 46.95, C_PRI, sw=1.2, rx=3)
circle(73.8, 41.8, 4.9, C_PRI, sw=0.8)
text(73.8, 42.4, "C1", 8.5, C_PRI, weight="bold")
text(73.8, 40.9, "100 µF 63 V SMD", 7, C_PRI)
text(73.8, 39.7, "VS ≈ 35 V", 7, C_PRI)
for tx, ty, tl in ((44.4, 33.4, "TP1 VS"), (47.6, 33.4, "TP2 C")):
    circle(tx, ty, 0.9, C_PRI, fill="#ffffff", sw=1.4)
    text(tx, ty - 2.2, tl, 6.5, C_PRI)

# U1: SIP standing, pin 1 at the right end (24 VAC side), outputs at the left end
rect(44.5, 38.8, 66.3, 48.0, C_PWR, fill=C_PWR, sw=1.0, opacity=0.12, rx=2)
rect(44.5, 38.8, 66.3, 48.0, C_PWR, sw=1.2, rx=2)
for px, pn, col in ((64.30, "1", C_PRI), (61.76, "2", C_PRI), (59.22, "3", C_PRI), (54.14, "5", C_FAINT),
                    (51.60, "6", C_PWR), (49.06, "7", C_GND), (46.52, "8", C_FAINT)):
    circle(px, 42.3, 0.75, C_PAD, fill=col, sw=0.8)
    text(px, 40.0, pn, 7, col)
text(50.4, 46.0, "U1  TMR 3-4811WI", 8.5, C_PWR, weight="bold")
text(50.4, 44.7, "5.1 V, 1.6 kV isolated", 7, C_PWR)
text(61.6, 46.0, "18–75 V in", 7, C_PRI)
text(62.4, 38.9 + 0.35, "−Vin +Vin Rem", 6.5, C_PRI)
text(50.3, 38.9 + 0.35, "−Vout +Vout", 6.5, C_PWR)
add(f'<line x1="{X(56.6):.1f}" y1="{Y(48.6):.1f}" x2="{X(56.6):.1f}" y2="{Y(38.2):.1f}" stroke="{C_PRI}" '
    f'stroke-width="1.6" stroke-dasharray="2 3"/>')

# ---- relays and their coil drive -----------------------------------------------------------------------------------
for ref, cx, call, pin, dref in (("K1", 26.0, "Y2", "D8", ("D3", "R5", "C7", "D4")),
                                 ("K2", 36.0, "W2", "D9", ("D5", "R6", "C8", "D6"))):
    for sx in (-3.5, 3.5):
        for sy in (-3.8, -1.6, 0.6, 3.8):
            rect(cx + sx - 0.9, 43.6 + sy - 0.4, cx + sx + 0.9, 43.6 + sy + 0.4, C_PAD, fill=C_PAD, sw=0.5)
    rect(cx - 3.25, 38.6, cx + 3.25, 48.6, C_RLY, fill=C_RLY, sw=1.0, opacity=0.15, rx=2)
    rect(cx - 3.25, 38.6, cx + 3.25, 48.6, C_RLY, sw=1.2, rx=2)
    text(cx, 44.6, ref, 9, C_RLY, weight="bold")
    text(cx, 43.2, "G6K-2F-Y", 6.5, C_RLY)
    text(cx, 42.1, "DC24", 6.5, C_RLY)
    text(cx, 47.0, f"→ {pin}", 6.5, C_IN, weight="bold")
    text(cx, 39.6, f"coil {call}", 6.5, C_PRI, weight="bold")
    d_rect, r_ser, c_res, d_fly = dref
    part(d_rect, cx - 2.6, 36.6, 3.7, 1.6, C_PRI, label_at="a")
    part(r_ser, cx + 2.6, 36.6, 2.0, 1.25, C_PRI, label_at="a")
    part(c_res, cx - 2.4, 33.7, 3.4, 2.7, C_PRI)
    part(d_fly, cx + 2.6, 33.7, 3.7, 1.6, C_PRI)

# ---- logic inputs: Y2 and W2 at the left, FAN and FLOW on the tab ------------------------------------------------
part("LED1", 4.0, 39.5, 2.0, 1.25, C_PWR, label_at="a")
part("R19", 8.0, 39.5, 2.0, 1.25, C_PWR, label_at="a")
text(14.4, 39.15, "PWR", 7, C_PWR, anchor="start", weight="bold")
for y, led, rl, rp, nm in ((45.5, "LED2", "R9", "R7", "Y2"), (42.5, "LED3", "R10", "R8", "W2")):
    part(led, 4.0, y, 2.0, 1.25, C_IN, label_at="a")
    part(rl, 8.0, y, 2.0, 1.25, C_IN, label_at="a")
    part(rp, 12.0, y, 2.0, 1.25, C_IN, label_at="a")
    text(14.4, y - 0.35, nm, 7, C_IN, anchor="start", weight="bold")

for ref, x, y in (("R11", 70.5, 33.6), ("R13", 73.5, 33.6), ("C9", 76.5, 33.6), ("R12", 70.5, 30.6),
                  ("LED4", 73.5, 30.6), ("R14", 70.5, 26.0), ("R15", 73.5, 26.0), ("C10", 76.5, 26.0)):
    part(ref, x, y, 2.0, 1.25, C_IN, label_at="a")
text(73.5, 28.3, "FAN → A2   FLOW → A3", 7, C_IN, weight="bold")

# ---- air temperatures -----------------------------------------------------------------------------------------------
for ref, x, y in (("R1", 49.0, 17.0), ("R3", 49.0, 13.0), ("C5", 49.0, 9.0),
                  ("R2", 54.0, 17.0), ("R4", 54.0, 13.0), ("C6", 54.0, 9.0)):
    part(ref, x, y, 1.25, 2.0, C_AN, label_at="a")
text(51.5, 20.1, "air temp. dividers", 7, C_AN, weight="bold")
text(51.5, 6.3, "→ A0      → A1", 7, C_AN)

# ---- 1-wire master -------------------------------------------------------------------------------------------------
part("U2", 72.8, 8.0, 6.2, 5.0, C_OW, "DS2482-100")
part("C4", 77.6, 8.0, 1.25, 2.0, C_OW, label_at="a")
part("F2", 73.5, 2.2, 4.8, 3.4, C_OW, "PTC 0.2 A")
for ref, x, y in (("R16", 71.0, 13.5), ("R17", 74.0, 13.5), ("R18", 77.0, 13.5)):
    part(ref, x, y, 2.0, 1.25, C_OW, label_at="a")
for ref, x, y in (("JP2", 71.0, 16.6), ("JP3", 74.0, 16.6), ("JP1", 77.0, 16.6)):
    part(ref, x, y, 2.0, 1.2, C_OW, label_at="a")
text(73.8, 20.4, "SDA · SCL from the top-left", 7, C_OW)

# ---- 5 V side of the converter ------------------------------------------------------------------------------------
part("C2", 50.3, 36.7, 3.2, 1.6, C_PWR)
part("C3", 54.0, 36.7, 3.2, 1.6, C_PWR)
for tx, ty, tl in ((13.6, 36.4, "TP3 +5"), (17.2, 36.4, "TP4 GND")):
    circle(tx, ty, 0.9, C_PWR if "+5" in tl else C_GND, fill="#ffffff", sw=1.4)
    text(tx, ty - 2.2, tl, 6.5, C_PWR if "+5" in tl else C_GND)

# ---- title block ----------------------------------------------------------------------------------------------------
cx, cy = 10.0, 22.0
circle(cx, cy, 4.6, "#555", sw=1.0)
text(cx, cy - 1.1, "DL", 16, "#555", weight="bold")
text(16.0, 24.0, "PIVAC AIR HANDLER NODE", 10, "#555", anchor="start", weight="bold")
text(16.0, 21.6, "v1.0 · Rev A · MBR shield", 8, "#555", anchor="start")
text(16.0, 19.4, "silkscreen only over the jack", 7, C_FAINT, anchor="start")

# ---- terminals on the tab ---------------------------------------------------------------------------------------------
TB = [("TB1", "MKDS 1/4-3,81", 79.06, 37.47, 52.71, [("R", 50.80), ("C", 46.99), ("Y2", 43.18), ("W2", 39.37)],
       C_PRI, "24 VAC from the Unico SCB thermostat block, 26–16 AWG"),
      ("TB2", "MPT 0,5/2", 80.16, 31.12, 36.20, [("FAN", 34.93), ("GND", 32.39)], C_IN,
       "SCB EAC dry contact: blower running (optional)"),
      ("TB3", "MPT 0,5/3", 80.16, 23.50, 31.12, [("+5", 29.85), ("SIG", 27.31), ("GND", 24.77)], C_IN,
       "coil water flow meter, pulse (future)"),
      ("TB4", "MPT 0,5/3", 80.16, 15.88, 23.50, [("SIG", 22.23), ("GND", 19.69), ("SH", 17.15)], C_AN,
       "supply-air 10K NTC, Belden 8451"),
      ("TB5", "MPT 0,5/3", 80.16, 8.26, 15.88, [("SIG", 14.61), ("GND", 12.07), ("SH", 9.53)], C_AN,
       "return-air 10K NTC, Belden 8451"),
      ("TB6", "MPT 0,5/3", 80.16, 0.64, 8.26, [("V", 6.99), ("D", 4.45), ("G", 1.91)], C_OW,
       "1-wire bus: DS18B20 water probes")]
for ref, kind, x0, y0, y1, pins, col, desc in TB:
    rect(x0, y0, BW, y1, col, fill=col, sw=1.0, opacity=0.14)
    rect(x0, y0, BW, y1, col, sw=1.3)
    for name, py in pins:
        px = x0 + 3.4
        circle(px, py, 0.95, C_PAD, fill="#ffffff", sw=1.2)
        rect(BW - 1.6, py - 0.9, BW, py + 0.9, col, fill="#ffffff", sw=0.8)
        text(BW + 1.2, py - 0.35, name, 9, col, anchor="start", weight="bold")
    mid = (y0 + y1) / 2
    text(BW + 7.6, mid + 0.6, f"{ref}  {kind}", 9, col, anchor="start", weight="bold")
    text(BW + 7.6, mid - 0.9, desc, 7.5, col, anchor="start")
    add(f'<line x1="{X(BW + 6.4):.1f}" y1="{Y(y0 + 0.3):.1f}" x2="{X(BW + 6.4):.1f}" y2="{Y(y1 - 0.3):.1f}" '
        f'stroke="{col}" stroke-width="1.4"/>')
text(BW + 0.3, BH + 1.3, "wire entries →", 8, "#555", anchor="end")

# ---- dimensions ---------------------------------------------------------------------------------------------------------
yd = -5.5
add(f'<line x1="{X(0):.1f}" y1="{Y(yd):.1f}" x2="{X(BW):.1f}" y2="{Y(yd):.1f}" stroke="#555" stroke-width="1"/>')
for xd in (0, UNO_W, BW):
    add(f'<line x1="{X(xd):.1f}" y1="{Y(yd - 1):.1f}" x2="{X(xd):.1f}" y2="{Y(yd + 1):.1f}" stroke="#555" '
        f'stroke-width="1"/>')
text(UNO_W / 2, yd + 0.6, "68.58 (R4)", 9, "#555")
text((UNO_W + BW) / 2, yd + 0.6, "17.78 tab, no R4 under it", 9, "#555")
text(BW / 2, yd - 2.0, "86.36", 10, "#333", weight="bold")
xd = -3.5
add(f'<line x1="{X(xd):.1f}" y1="{Y(0):.1f}" x2="{X(xd):.1f}" y2="{Y(BH):.1f}" stroke="#555" stroke-width="1"/>')
text(xd - 0.8, BH / 2, "53.34", 10, "#333", weight="bold", rotate=-90)

# ---- legend ------------------------------------------------------------------------------------------------------------
ly = Y(0) + 105
items = [(C_PRI, "24 VAC side: entry, half-wave rectifiers, relay coils"), (C_RLY, "relays, coil to contact 1.5 kV"),
         (C_PWR, "5.1 V from the converter to the R4's 5V pin"), (C_IN, "logic inputs Y2, W2, FAN, FLOW"),
         (C_AN, "air-temperature dividers"), (C_OW, "I2C to 1-wire master"),
         (C_FAINT, "dashed grey: the R4 under the shield; keep its area clear of leads")]
for i, (col, lab) in enumerate(items):
    lx = BX + (i % 2) * 430
    yy = ly + (i // 2) * 22
    add(f'<rect x="{lx}" y="{yy - 11}" width="16" height="12" fill="{col}" fill-opacity="0.25" stroke="{col}"/>')
    add(f'<text x="{lx + 24}" y="{yy}" font-size="11" fill="#222" font-family="Helvetica, Arial, sans-serif">'
        f'{lab}</text>')
notes = ["Header pins used: 5V (supply in from U1), GND, A0 A1 air, A2 FAN, A3 FLOW, SDA SCL to U2, D8 Y2, D9 W2, "
         "D2 only through JP1 (1-wire rollback).",
         "U1, C1 and the terminals stand 9–16 mm tall: a second shield stacked above needs extended headers.",
         "Primary bus R · C · Y2 · W2 runs on the solder side; +5 from U1 pin 6 crosses it on the component side."]
for i, n in enumerate(notes):
    add(f'<text x="{BX}" y="{ly + 92 + i * 18}" font-size="11" fill="#444" '
        f'font-family="Helvetica, Arial, sans-serif">{n}</text>')

add("</svg>")
Path(__file__).with_name("mbr-air-handler-shield-pcb-layout.svg").write_text("\n".join(out) + "\n")
print("wrote docs/mbr-air-handler-shield-pcb-layout.svg")
