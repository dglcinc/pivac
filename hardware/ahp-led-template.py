"""Write a 1:1 drill template for the six status-LED holes in the 1593K base's left wall, as a letter-size PDF.

    python3 hardware/ahp-led-template.py hardware/ahp-board/ahp-led-drill-template.pdf

The hole positions come from the same geometry hardware/ahp-box-models.py drills in its render: each LED sits at
board y 26.5 ... 46.5 mm, the board's centre is the box's centre (board y 28), and the hole centres stand 6.7 mm above
the base's outside bottom face. The strip is the base half of the wall, 67.22 mm long and 14 mm tall, drawn as seen
from outside the left wall with the floor down, which puts the USB-A end on the left. Print at 100 % (actual size)
and check the 50 mm bar before cutting.
"""
import math
import sys

MM = 72 / 25.4
L, HB, ZH, D = 67.22, 14.0, 6.7, 3.0          # wall length, base half height, hole height, hole diameter
LEDS = [("PWR", "green", 26.5), ("FAN", "yellow", 30.5), ("Y1", "blue", 34.5),
        ("Y2", "blue", 38.5), ("W1", "red", 42.5), ("W2", "red", 46.5)]

ops = []
def mv(x, y): ops.append(f"{x * MM:.2f} {y * MM:.2f} m")
def ln(x, y): ops.append(f"{x * MM:.2f} {y * MM:.2f} l")
def stroke(w=0.25, dash=None):
    ops.append(f"{w * MM:.2f} w " + (f"[{dash * MM:.2f}] 0 d " if dash else "[] 0 d ") + "S")
def line(x0, y0, x1, y1, w=0.25, dash=None):
    mv(x0, y0); ln(x1, y1); stroke(w, dash)
def circle(cx, cy, r, w=0.25):
    k = 0.5523 * r
    pts = [(cx + r, cy), (cx + r, cy + k, cx + k, cy + r, cx, cy + r), (cx - k, cy + r, cx - r, cy + k, cx - r, cy),
           (cx - r, cy - k, cx - k, cy - r, cx, cy - r), (cx + k, cy - r, cx + r, cy - k, cx + r, cy)]
    mv(*pts[0])
    for p in pts[1:]:
        ops.append(" ".join(f"{v * MM:.2f}" for v in p) + " c")
    stroke(w)
def text(x, y, s, size=9, bold=False):
    s = s.replace("\\", "\\\\").replace("(", "\\(").replace(")", "\\)")
    ops.append(f"BT /{'F2' if bold else 'F1'} {size} Tf {x * MM:.2f} {y * MM:.2f} Td ({s}) Tj ET")

PW, PH = 215.9, 279.4
X0, Y0 = (PW - L) / 2, 150.0                  # strip's lower left: USB-A end, outside bottom face

text(20, 255, "AirMaster Rev B: LED drill template, 1593K base, left wall", 13, True)
text(20, 248, "Print at 100 % / Actual size. The bar below must measure 50 mm; if not, do not use the print.", 9)
line(20, 238, 70, 238, 0.4)
for x in (20, 70):
    line(x, 236, x, 240, 0.4)
text(38, 233, "50 mm", 8)

# the strip
mv(X0, Y0); ln(X0 + L, Y0); ln(X0 + L, Y0 + HB); ln(X0, Y0 + HB); ops.append("h"); stroke(0.35)
line(X0 + L / 2, Y0 - 4, X0 + L / 2, Y0 + HB + 4, 0.2, 1.0)
text(X0 + L / 2 - 6, Y0 + HB + 6, "box centre", 7)
text(X0 - 2, Y0 + HB + 6, "USB-A end", 8, True)
text(X0 + L - 16, Y0 + HB + 6, "sensor end", 8, True)
text(X0, Y0 - 6, "bottom edge = outside face of the base's floor", 8)
text(X0 + 2, Y0 + HB - 4, "seam (top edge of the base)", 7)
for xv, yv in ((X0, Y0 + HB + 2), (X0 + L, Y0 + HB + 2)):
    line(xv, Y0 - 2, xv, Y0 + HB + 2, 0.35)

for i, (name, col, by) in enumerate(LEDS):
    x = X0 + L / 2 + (by - 28.0)              # board y grows toward the sensor end, which is on the right
    y = Y0 + ZH
    circle(x, y, D / 2, 0.3)
    line(x - 2.5, y, x + 2.5, y, 0.15)
    line(x, y - 2.5, x, y + 2.5, 0.15)
    text(x - 2.2, Y0 + 1.2 if i % 2 == 0 else Y0 + ZH + 3.0, name, 5.5, True)

text(20, 130, "1. Cut along the strip's outline. The two end lines are the box's outer ends, 67.22 mm apart.", 9)
text(20, 124, "2. Tape the strip to the left wall of the BASE (the half with the floor and the posts), outside,", 9)
text(20, 119.5, "   bottom edge on the floor's outside edge, the USB-A end toward the panel notched for J4 and micro-USB.", 9)
text(20, 114, "   Centre the box-centre line on the wall; the end lines then fall on the rounded corners.", 9)
text(20, 108, "3. Centre-punch each cross, drill 1.5 mm, then 3 mm. Plastic: low speed, light pressure.", 9)
text(20, 102, "4. Holes are 4 mm apart, 6.7 mm above the outside bottom face. From the USB-A end:", 9)
text(20, 97.5, "   PWR green, FAN yellow, Y1 blue, Y2 blue, W1 red, W2 red.", 9)
text(20, 91, "Generated by hardware/ahp-led-template.py.", 7)

content = "\n".join(ops).encode()
objs = [b"<< /Type /Catalog /Pages 2 0 R >>",
        b"<< /Type /Pages /Kids [3 0 R] /Count 1 >>",
        (f"<< /Type /Page /Parent 2 0 R /MediaBox [0 0 {PW * MM:.0f} {PH * MM:.0f}] "
         f"/Resources << /Font << /F1 4 0 R /F2 5 0 R >> >> /Contents 6 0 R >>").encode(),
        b"<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica >>",
        b"<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica-Bold >>",
        b"<< /Length %d >>\nstream\n" % len(content) + content + b"\nendstream"]
out = bytearray(b"%PDF-1.4\n")
offs = []
for i, o in enumerate(objs, 1):
    offs.append(len(out)); out += b"%d 0 obj\n" % i + o + b"\nendobj\n"
x = len(out)
out += b"xref\n0 %d\n0000000000 65535 f \n" % (len(objs) + 1) + b"".join(b"%010d 00000 n \n" % o for o in offs)
out += b"trailer\n<< /Size %d /Root 1 0 R >>\nstartxref\n%d\n%%%%EOF\n" % (len(objs) + 1, x)
open(sys.argv[1], "wb").write(out)
print("wrote", sys.argv[1], [round(L / 2 + (by - 28.0), 2) for _, _, by in LEDS])
